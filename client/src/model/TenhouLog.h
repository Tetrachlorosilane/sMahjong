#pragma once

// **天鳳牌譜导出（tenhou.net/6 原生 JSON）**。
//
// 这一份是 `mjai-reviewer` / Mortal 之类工具**唯一能吃**的输入格式
// （`docs/input-json.md` 是它的逐字段规格；下面每个细节都对着参考实现
//  `Equim-chan/mjai-reviewer` 的 `convlog/src/{tenhou/json_scheme.rs, tenhou/log.rs, conv.rs}` 核过）：
//
//   {
//     "title": ["四人麻雀","<GMT 时间>"],          // 可选（解析器忽略未知字段）
//     "name":  ["东家名","南家名","西家名","北家名"],  // 必填、恰好 4 个；**座位 0 = 起家**，全程不轮转
//     "rule":  {"disp":"般南喰赤","aka51":1,"aka52":1,"aka53":1},
//     "log":   [ [ 小局0 ], [ 小局1 ], ... ]        // 必须是数组、字段名就叫 log
//   }
//
// 每个小局 = **位置固定的 17 元组**：
//   [0] [场局次, 本场, 供託]      场局次：0..3 = 東1..東4，4..7 = 南1..南4（**从 0 开始**）
//   [1] [四家点数]
//   [2] 表ドラ指示牌（含杠后追加的，**第一个必填**；个数 ≥ 1 + 杠数）
//   [3] 裏ドラ指示牌（和了时整组给出；没和了就空数组）
//   [4..6]   0 号位：配牌（**恰好 13 张**）、取、出
//   [7..9]   1 号位；[10..12] 2 号位；[13..15] 3 号位
//   [16] 结果（见下）
//
// 牌码 = **整数**：11..19 = 1m..9m、21..29 = 1p..9p、31..39 = 1s..9s、41..47 = 東南西北白發中、
// **51/52/53 = 赤五 m/p/s**；`0` = 未知牌（只用作**大明杠在出牌表里留的空位**）；
// `60` = **摸切占位**（只能出现在「出」表里，且必须有一手摸牌可回填）。
//
// 「取」`takes` / 「出」`discards` 的元素（`docs/input-json.md` §5–§6，判据照抄参考实现）：
//   · 整数 = 摸到/打出的牌；`60` = 摸切；`"r<码>"` / `"r60"` = 立直宣言（占一个元素）
//   · 鸣牌字符串：**关键字后面紧挨着的那张就是被鸣的牌**，关键字位置编码来源
//     （上家 = 关键字在 [0] / 対面 = [2] / 下家 = 碰·加杠在 [4]、大明杠在 [6]）：
//       吃   `c` + 3 张 ×2 位 = 7 字符（吃只能来自上家）
//       碰   `p` + 3 张 ×2 位 = 7 字符
//       大明杠 `m` + 4 张 ×2 位 = 9 字符（**写在 takes 里**，并在 discards 里放一个 `0` 空位）
//       加杠 `k` + 4 张 ×2 位 = 9 字符（写在 discards 里）
//       暗杠 `a` **只能**在 [6]：前三个两张一组 + `a` + 第 4 张（写在 discards 里）
//   · 配对关系（参考实现的 `finalize_discards`）：立直占一个元素但产生两个事件；
//     摸切从同一手摸牌回填；大明杠那个 `0` 会被删掉 —— 所以**有大明杠的那家 takes 比 discards 多 1** 是正常的。
//
// 结果 `results`（参考实现的 `log.rs`）：
//   和了 → `["和了", [四家点数增减], [和了家, 放銃家, "30符4飜7700点", …], …]`
//          （自摸时第 2 个元素 = 和了家；明细节**只有前两个元素**被读取，其余随便写）
//   流局 → `["流局", [四家点数增减]]`，途中流局写 `["九種九牌"]` 这类状态字即可（**只有 "和了" 是魔法串**）
//
//   ⚠ 这里的「四家点数增减」是**净变化**（= 结算后四家点数 − 上一次结算后的点数），取自协议的
//     `scores_after`，**不是** `score_delta`：后者不含各家**自己立直扣掉的那 1000 点**，
//     抄它会让点数板与差分对不上、日志里四家点数之和每根立直棒多 1000（NOTES §9.6.1）。
//
// ⚠ 如实说明的两条：
//   ① 東風戦照实把 `disp` 写成带「東」的形式 —— 参考实现据此判为東風戦并**明确拒绝**（Mortal 只支持半庄）。
//      这比假装半庄、让引擎按半庄算错要好。
//   ② 和了明细里的符/飜/点数是**给人看的文字**（解析器不读）；役种名不写（天鳳的役种是数字 id，
//      我们没有那张表的权威来源，写错等于报错役）。和了家/放銃家/收支/宝牌/里宝都在。

#include <QString>
#include <QStringList>

class ReplayModel;

class TenhouLog
{
public:
    struct Result
    {
        bool ok = false;
        QString json;          // 牌谱 JSON（可直接拼进链接）
        QString url;           // https://tenhou.net/6/#json=<json>
        QStringList problems;  // 导出过程中发现的问题（小局级，不致命）
        int rounds = 0;        // 导出的小局数
    };

    /** 把我们记录的整场导出成天鳳牌譜。任何小局级的小毛病都不致命，只会记进 `problems`。 */
    static Result build(const ReplayModel& rp);

    /** 牌码 → 天鳳牌号（"1m"→11 … "0s"→53）；认不出的返回 -1。 */
    static int tileNumber(const QString& code);

    // ================= 完整天鳳牌谱（mjlog XML）=================
    //
    // `#json=` 那份是**查看器用的瘦格式**（没有副露）；这一份是天鳳原生的 `mjlog` XML，
    // **完整**：配牌、每一张摸牌/打牌、鸣牌（吃碰杠/暗杠/加杠）、立直宣言、杠宝牌、
    // 和了与流局全部带着。标签与位域编码都按公开实现核对过（mjlog2mjai / mjlog2json /
    // tenhou 的 `tehai.js` 反解公式），关键几条：
    //   · 摸牌/打牌把**牌号写在标签名里**：`<T{id}/>`…`<W{id}/>` = 0..3 家摸牌，
    //     `<D{id}/>`…`<G{id}/>` = 0..3 家打牌（`id` 是 0..135 的**唯一**牌号）。
    //     所以**摸切的牌号必须与刚摸到的那张相同** —— 我们按这个不变量分配牌号。
    //   · `<N who m/>` 的 `m` 是位域打包：`m&0x3` = 被鸣者相对座位（0=上家/3=自己=暗杠），
    //     `0x4` 吃 / `0x8` 碰 / `0x10` 加杠 / `0x20` 拔北；吃是 `(pattern<<10)|三家副本偏移`，
    //     碰/加杠是 `(pattern<<9)|(缺的那张副本<<5)`，`pattern = 种类*3 + 被鸣牌在其中的序号`；
    //     杠是 `(代表牌号<<8)|相对座位`。
    //   · 立直：`<REACH who step="1"/>` 在**宣言牌之前**、`step="2"` 在其后。
    //
    // ⚠ 两处**如实说明**的限制（不是漏做，是数据/格式本身如此）：
    //   ① **不写 `<SHUFFLE>`（牌山）**：天鳳把整副牌山打包成一个 seed，那个编码没有公开规范；
    //      而本格式里每一次摸牌都带牌号，**牌山本来就是冗余的**，不写不影响任何消费方还原牌局。
    //   ② **不写 `yaku` 属性**：天鳳的役种是数字 id，那张表我无法在此环境核对；写错等于报错役。
    //      （和了/流局的家、手牌、和了牌、宝牌/里宝、符数/点数/收支都在。）
    struct MjlogResult
    {
        bool ok = false;
        QString xml;
        QStringList problems;
        int rounds = 0;
        int tiles = 0;   // 分配出去的牌号数（自检用来核"每个牌号最多用一次"）
    };

    /** 生成完整天鳳牌谱（mjlog XML）。 */
    static MjlogResult buildMjlog(const ReplayModel& rp);

    /** 写出 mjlog 文件（UTF-8，带 XML 声明）。 */
    static bool writeMjlogFile(const MjlogResult& r, const QString& path, QString* err = nullptr);

    /**
     * 解一条 `m`（**照抄参考实现的解码公式**，只给自检用）：
     * 返回被鸣的几张牌号 + 被鸣者相对座位；`kind` 回填 "chi"/"pon"/"kakan"/"kan"。
     * 这是"我编的位域必须能被公开实现解回来"的判据。
     */
    static QVector<int> decodeMeldForTest(int m, QString* kind, int* dir);

    /**
     * 写出到文件（`.txt`，内容 = 那一行链接 + 缩进过的 JSON —— 便于人肉查看）。
     * @param path 目标文件；父目录不存在会创建
     */
    static bool writeFile(const Result& r, const QString& path, QString* err = nullptr);

    /**
     * 写出**纯 JSON 文件**（`.json`）—— 这一份才可以直接喂 `mjai-reviewer`：
     *   `mjai-reviewer -e mortal -i <文件>.json -a <自己的座位 0..3>`
     * （`.txt` 那份第一行是链接，工具解析不了。）
     */
    static bool writeJsonFile(const Result& r, const QString& path, QString* err = nullptr);
};
